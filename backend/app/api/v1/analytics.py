"""Analytics and Incident Candidates API endpoints."""

import uuid

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from app.analytics.engine import OperationsIntelligenceEngine
from app.core.logging import get_logger
from app.database.session import get_db
from app.schemas.analytics import (
    AnalyticsRunRequest,
    AnalyticsRunResponse,
    IncidentCandidateResponse,
)

logger = get_logger("aegis.api.analytics")

router = APIRouter(prefix="/analytics", tags=["Analytics"])
candidates_router = APIRouter(prefix="/incident-candidates", tags=["Incident Candidates"])


@router.post(
    "/run",
    response_model=AnalyticsRunResponse,
    status_code=status.HTTP_200_OK,
    summary="Trigger analytics anomaly detection & correlation run",
    description="Executes all modular detectors, scoring, deduplication, operational correlation, and business impact estimation.",
)
def trigger_analytics_run(
    payload: AnalyticsRunRequest,
    db: Session = Depends(get_db),
) -> AnalyticsRunResponse:
    """Executes the Operations Intelligence Engine pipeline."""
    try:
        engine = OperationsIntelligenceEngine()
        record = engine.run_analysis(
            db=db,
            company_id=payload.company_id,
            start_time=payload.start_time,
            end_time=payload.end_time,
            metric_filter=payload.metric_filter,
        )
        data = record.to_dict()
        return AnalyticsRunResponse.model_validate(data)
    except Exception as exc:
        logger.exception(f"Error executing analytics run: {exc}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Analytics run failed: {exc}",
        ) from exc


@router.get(
    "/status",
    response_model=list[AnalyticsRunResponse],
    status_code=status.HTTP_200_OK,
    summary="Get analytics run history & status",
    description="Returns recent analytics execution records including status, duration, anomaly counts, and candidate counts.",
)
def get_analytics_status(
    limit: int = Query(default=10, ge=1, le=100, description="Max runs to return"),
) -> list[AnalyticsRunResponse]:
    """Retrieves recent analytics pipeline execution records."""
    runs = OperationsIntelligenceEngine.get_run_history()
    recent = list(reversed(runs))[:limit]
    return [AnalyticsRunResponse.model_validate(r.to_dict()) for r in recent]


@candidates_router.get(
    "",
    response_model=list[IncidentCandidateResponse],
    status_code=status.HTTP_200_OK,
    summary="List correlated incident candidates",
    description="Retrieve incident candidates generated by multi-metric operational correlation with preliminary business blast radius.",
)
def list_incident_candidates(
    company_id: uuid.UUID | None = Query(
        default=None, description="Filter candidates by company UUID"
    ),
) -> list[IncidentCandidateResponse]:
    """Retrieves correlated incident candidates."""
    candidates = OperationsIntelligenceEngine.get_incident_candidates(company_id=company_id)
    return [IncidentCandidateResponse.model_validate(c.to_dict()) for c in candidates]
